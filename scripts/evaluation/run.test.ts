import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import sharp from 'sharp';

test('baseline pipeline produces deterministic ranks and rejects invalid datasets', async () => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'shape-evaluation-'));
  const root = path.resolve(import.meta.dirname, '../..');
  const index = JSON.parse(await readFile(path.join(root, 'src/data/icons/index-lucide.json'), 'utf8'));
  const icon = index.icons.find((item: { id: string }) => item.id.includes('circle')) ?? index.icons[0];
  await sharp(Buffer.from(icon.svg)).resize(128, 128).flatten({ background: '#fff' }).png().toFile(path.join(directory, 'query.png'));
  const sample = { id: 'smoke', image: 'query.png', kind: 'synthetic', split: 'dev', author: 'smoke-test', group: 'smoke-icon', strict: [icon.id], acceptable: [icon.id], tags: ['smoke'] };
  const manifest = path.join(directory, 'dataset.json');
  const output = path.join(directory, 'report.json');
  const run = (...args: string[]) => spawnSync(process.execPath, ['--import', 'tsx', path.join(root, 'scripts/evaluation/run.ts'), '--dataset', manifest, '--out', output, ...args], { cwd: root, encoding: 'utf8' });
  const setSamples = (samples: unknown[]) => writeFile(manifest, JSON.stringify({ version: 1, seed: 20261012, samples }));
  await setSamples([sample]);
  let result = run();
  assert.equal(result.status, 0, result.stderr);
  const first = JSON.parse(await readFile(output, 'utf8'));
  assert.equal(first.phaseOneComplete, false);
  assert.equal(first.gates.realSampleCount, false);
  assert.equal(first.summaries.find((s: { kind: string; split: string }) => s.kind === 'synthetic' && s.split === 'dev').count, 1);
  assert.ok(first.rows[0].strictRank > 0);
  result = run();
  assert.equal(result.status, 0, result.stderr);
  const second = JSON.parse(await readFile(output, 'utf8'));
  assert.deepEqual(first.rows[0].top10, second.rows[0].top10);
  assert.deepEqual(first.indexHashes, second.indexHashes);
  assert.equal(first.rows[0].strictRank, second.rows[0].strictRank);
  assert.equal(run('--require-ready').status, 2);
  await setSamples([{ ...sample, strict: ['nonexistent'] }]);
  assert.match(run().stderr, /Invalid labels/);
  await setSamples([sample, { ...sample, id: 'leak', split: 'test' }]);
  assert.match(run().stderr, /Group leakage/);
  await setSamples([sample, { ...sample, id: 'duplicate-image', group: 'another' }]);
  assert.match(run().stderr, /Duplicate image/);
  await setSamples([]);
  assert.match(run().stderr, /No labeled samples/);
});
